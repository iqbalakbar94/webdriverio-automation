import { LoginData } from '../../../../pageobjects/web/sauce-demo/auth/login.page'
import { AuthService } from '../../../../services/web/sauce-demo/auth.service'
import InventoryPage from '../../../../pageobjects/web/sauce-demo/product/inventory.page'
import CartPage from '../../../../pageobjects/web/sauce-demo/checkout/cart.page'

describe('Scenario Test - Sauce Demo - Cart Page', () => {
    let loginFixtures: Record<string, LoginData>
    before(async () => {
        const fixtureData = await import(`../../../../fixtures/${process.env.ENV_NAME}/web/sauce-demo/login.json`)
        loginFixtures = fixtureData || fixtureData.default
    })

    beforeEach(async () => {
        await AuthService.login(loginFixtures.standardUser)
        await browser.execute(() => {
            window.localStorage.clear()
            window.sessionStorage.clear()
        })
        await browser.refresh()
    })

    describe('Positive Case', () => {
        it('TC-SCA-001 : [Positive] Tampilan page Cart dengan kondisi memiliki 1 product yang dipilih', async () => {
            const actualProductNamesLabel = await InventoryPage.getAllProductNamesLabel()
            const actualProductDescLabel = await InventoryPage.getAllProductDescLabel()
            const actualProductPricesLabel = await InventoryPage.getAllProductPricesLabel()

            await InventoryPage.clickAddToCartButton(0)
            await InventoryPage.header.clickShoppingCartLink()
            await expect(browser).toHaveUrl(expect.stringContaining('/cart.html'))
            await expect(CartPage.header.titleLabel).toHaveText('Swag Labs')
            await expect(CartPage.header.sidebarMenuButton).toBeDisplayed()
            await expect(CartPage.header.shoppingCartLink).toBeDisplayed()
            await expect(CartPage.header.shoppingCartBadgeLabel).toHaveText('1')
            await expect(CartPage.productQuantityLabel[0]).toHaveText('1')
            await expect(CartPage.productNamesLabel).toHaveText(actualProductNamesLabel[0])
            await expect(CartPage.productDescLabel).toHaveText(actualProductDescLabel[0])
            await expect(CartPage.productPricesLabel).toHaveText(actualProductPricesLabel[0])
            await expect(CartPage.removeFromCartButton).toBeDisplayed()
            await expect(CartPage.checkoutButton).toBeDisplayed()
            await expect(CartPage.footer.socialXLink).toBeDisplayed()
            await expect(CartPage.footer.socialFacebookLink).toBeDisplayed()
            await expect(CartPage.footer.socialLinkedInLink).toBeDisplayed()
            await expect(CartPage.footer.footerLabel).toBeDisplayed()
        })

        it('TC-SCA-002 : [Positive] Tampilan page Cart dengan kondisi memiliki lebih dari 1 product yang dipilih', async () => {
            const actualProductNamesLabel = await InventoryPage.getAllProductNamesLabel()
            const actualProductDescLabel = await InventoryPage.getAllProductDescLabel()
            const actualProductPricesLabel = await InventoryPage.getAllProductPricesLabel()

            await InventoryPage.clickAddToCartButton(0)
            await InventoryPage.clickAddToCartButton(0)
            await InventoryPage.header.clickShoppingCartLink()
            await expect(browser).toHaveUrl(expect.stringContaining('/cart.html'))
            await expect(CartPage.header.titleLabel).toHaveText('Swag Labs')
            await expect(CartPage.header.sidebarMenuButton).toBeDisplayed()
            await expect(CartPage.header.shoppingCartLink).toBeDisplayed()
            await expect(CartPage.header.shoppingCartBadgeLabel).toHaveText('2')
            await expect(CartPage.productQuantityLabel[0]).toHaveText('1')
            await expect(CartPage.productQuantityLabel[1]).toHaveText('1')
            await expect(CartPage.productNamesLabel[0]).toHaveText(actualProductNamesLabel[0])
            await expect(CartPage.productNamesLabel[1]).toHaveText(actualProductNamesLabel[1])
            await expect(CartPage.productDescLabel[0]).toHaveText(actualProductDescLabel[0])
            await expect(CartPage.productDescLabel[1]).toHaveText(actualProductDescLabel[1])
            await expect(CartPage.productPricesLabel[0]).toHaveText(actualProductPricesLabel[0])
            await expect(CartPage.productPricesLabel[1]).toHaveText(actualProductPricesLabel[1])
            await expect(CartPage.removeFromCartButton[0]).toBeDisplayed()
            await expect(CartPage.removeFromCartButton[1]).toBeDisplayed()
            await expect(CartPage.checkoutButton).toBeDisplayed()
            await expect(CartPage.footer.socialXLink).toBeDisplayed()
            await expect(CartPage.footer.socialFacebookLink).toBeDisplayed()
            await expect(CartPage.footer.socialLinkedInLink).toBeDisplayed()
            await expect(CartPage.footer.footerLabel).toBeDisplayed()
        })

        it('TC-SCA-003 : [Positive] Tampilan page Cart dengan kondisi tanpa product yang dipilih', async () => {
            await InventoryPage.header.clickShoppingCartLink()
            await expect(browser).toHaveUrl(expect.stringContaining('/cart.html'))
            await expect(CartPage.header.titleLabel).toHaveText('Swag Labs')
            await expect(CartPage.header.sidebarMenuButton).toBeDisplayed()
            await expect(CartPage.header.shoppingCartLink).toBeDisplayed()
            await expect(CartPage.header.shoppingCartBadgeLabel).not.toBeDisplayed()
            await expect(await CartPage.productQuantityLabel).toHaveLength(0)
            await expect(await CartPage.productNamesLabel).toHaveLength(0)
            await expect(await CartPage.productDescLabel).toHaveLength(0)
            await expect(await CartPage.productPricesLabel).toHaveLength(0)
            await expect(await CartPage.removeFromCartButton).toHaveLength(0)
            await expect(CartPage.checkoutButton).toBeDisplayed()
            await expect(CartPage.footer.socialXLink).toBeDisplayed()
            await expect(CartPage.footer.socialFacebookLink).toBeDisplayed()
            await expect(CartPage.footer.socialLinkedInLink).toBeDisplayed()
            await expect(CartPage.footer.footerLabel).toBeDisplayed()
        })

        it('TC-SCA-004 : [Positive] Menghapus 1 dari 2 product yang sudah ada di keranjang', async () => {
            const actualProductNamesLabel = await InventoryPage.getAllProductNamesLabel()
            const actualProductDescLabel = await InventoryPage.getAllProductDescLabel()
            const actualProductPricesLabel = await InventoryPage.getAllProductPricesLabel()

            await InventoryPage.clickAddToCartButton(0)
            await InventoryPage.clickAddToCartButton(0)
            await InventoryPage.header.clickShoppingCartLink()
            await expect(browser).toHaveUrl(expect.stringContaining('/cart.html'))
            await expect(CartPage.header.shoppingCartBadgeLabel).toBeDisplayed()
            await expect(CartPage.header.shoppingCartBadgeLabel).toHaveText('2')
            await expect(CartPage.productQuantityLabel[0]).toHaveText('1')
            await expect(CartPage.productQuantityLabel[1]).toHaveText('1')
            await expect(CartPage.productNamesLabel[0]).toHaveText(actualProductNamesLabel[0])
            await expect(CartPage.productNamesLabel[1]).toHaveText(actualProductNamesLabel[1])
            await expect(CartPage.productDescLabel[0]).toHaveText(actualProductDescLabel[0])
            await expect(CartPage.productDescLabel[1]).toHaveText(actualProductDescLabel[1])
            await expect(CartPage.productPricesLabel[0]).toHaveText(actualProductPricesLabel[0])
            await expect(CartPage.productPricesLabel[1]).toHaveText(actualProductPricesLabel[1])
            await expect(CartPage.removeFromCartButton[0]).toBeDisplayed()
            await expect(CartPage.removeFromCartButton[1]).toBeDisplayed()

            await CartPage.clickRemoveFromCartButton(0)
            await expect(CartPage.header.shoppingCartBadgeLabel).toHaveText('1')
            await expect(await CartPage.productQuantityLabel).toHaveLength(1)
            await expect(CartPage.productQuantityLabel[0]).toHaveText('1')
            await expect(await CartPage.productNamesLabel).toHaveLength(1)
            await expect(CartPage.productNamesLabel[0]).toHaveText(actualProductNamesLabel[1])
            await expect(await CartPage.productDescLabel).toHaveLength(1)
            await expect(CartPage.productDescLabel[0]).toHaveText(actualProductDescLabel[1])
            await expect(await CartPage.productPricesLabel).toHaveLength(1)
            await expect(CartPage.productPricesLabel[0]).toHaveText(actualProductPricesLabel[1])
            await expect(await CartPage.removeFromCartButton).toHaveLength(1)
            await expect(CartPage.removeFromCartButton[0]).toBeDisplayed()
        })

        it('TC-SCA-005 : [Positive] Menghapus semua product yang sudah ada di keranjang', async () => {
            const actualProductNamesLabel = await InventoryPage.getAllProductNamesLabel()
            const actualProductDescLabel = await InventoryPage.getAllProductDescLabel()
            const actualProductPricesLabel = await InventoryPage.getAllProductPricesLabel()

            await InventoryPage.clickAddToCartButton(0)
            await InventoryPage.clickAddToCartButton(0)
            await InventoryPage.header.clickShoppingCartLink()
            await expect(browser).toHaveUrl(expect.stringContaining('/cart.html'))
            await expect(CartPage.header.shoppingCartBadgeLabel).toBeDisplayed()
            await expect(CartPage.header.shoppingCartBadgeLabel).toHaveText('2')
            await expect(CartPage.productQuantityLabel[0]).toHaveText('1')
            await expect(CartPage.productQuantityLabel[1]).toHaveText('1')
            await expect(CartPage.productNamesLabel[0]).toHaveText(actualProductNamesLabel[0])
            await expect(CartPage.productNamesLabel[1]).toHaveText(actualProductNamesLabel[1])
            await expect(CartPage.productDescLabel[0]).toHaveText(actualProductDescLabel[0])
            await expect(CartPage.productDescLabel[1]).toHaveText(actualProductDescLabel[1])
            await expect(CartPage.productPricesLabel[0]).toHaveText(actualProductPricesLabel[0])
            await expect(CartPage.productPricesLabel[1]).toHaveText(actualProductPricesLabel[1])
            await expect(CartPage.removeFromCartButton[0]).toBeDisplayed()
            await expect(CartPage.removeFromCartButton[1]).toBeDisplayed()

            await CartPage.clickRemoveFromCartButton(1)
            await CartPage.clickRemoveFromCartButton(0)
            await expect(CartPage.header.shoppingCartBadgeLabel).not.toBeDisplayed()
            await expect(await CartPage.productQuantityLabel).toHaveLength(0)
            await expect(await CartPage.productNamesLabel).toHaveLength(0)
            await expect(await CartPage.productDescLabel).toHaveLength(0)
            await expect(await CartPage.productPricesLabel).toHaveLength(0)
            await expect(await CartPage.removeFromCartButton).toHaveLength(0)
        })

        it('TC-SCA-006 : [Positive] Melanjutkan pilih product lainnya dengan kembali ke page Inventory', async () => {
            const actualProductNamesLabel = await InventoryPage.getAllProductNamesLabel()
            const actualProductDescLabel = await InventoryPage.getAllProductDescLabel()
            const actualProductPricesLabel = await InventoryPage.getAllProductPricesLabel()

            await InventoryPage.clickAddToCartButton(0)
            await InventoryPage.header.clickShoppingCartLink()
            await expect(browser).toHaveUrl(expect.stringContaining('/cart.html'))
            await expect(CartPage.header.shoppingCartLink).toBeDisplayed()
            await expect(CartPage.header.shoppingCartBadgeLabel).toHaveText('1')
            await expect(CartPage.productQuantityLabel[0]).toHaveText('1')
            await expect(CartPage.productNamesLabel).toHaveText(actualProductNamesLabel[0])
            await expect(CartPage.productDescLabel).toHaveText(actualProductDescLabel[0])
            await expect(CartPage.productPricesLabel).toHaveText(actualProductPricesLabel[0])
            await expect(CartPage.removeFromCartButton).toBeDisplayed()

            await CartPage.clickContinueShoppingButton()
            await expect(browser).toHaveUrl(expect.stringContaining('/inventory.html'))
            await expect(InventoryPage.header.shoppingCartLink).toBeDisplayed()
            await expect(InventoryPage.header.shoppingCartBadgeLabel).toHaveText('1')
        })
    })
})